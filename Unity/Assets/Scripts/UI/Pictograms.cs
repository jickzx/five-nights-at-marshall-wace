        static readonly Dictionary<string, Texture2D> Cache = new Dictionary<string, Texture2D>();

        public static bool Has(string word) => Resolve(word) != null;

        static string Resolve(string word)
        {
            word = (word ?? "").Trim().ToLowerInvariant();
            if (Art.ContainsKey(word)) return word;
            return Alias.TryGetValue(word, out var a) ? a : null;
        }

        /// <summary>Picture for a word, or null when there is none.</summary>
        public static Texture2D Get(string word)
        {
            var key = Resolve(word);
            if (key == null) return null;
            if (Cache.TryGetValue(key, out var tex) && tex) return tex;
            var rows = Art[key];
            tex = new Texture2D(Size, Size, TextureFormat.RGBA32, false)
            { filterMode = FilterMode.Point, wrapMode = TextureWrapMode.Clamp, hideFlags = HideFlags.HideAndDontSave };
            var px = new Color32[Size * Size];
            for (int y = 0; y < Size; y++)
            {
                string row = y < rows.Length ? rows[y] : "";
                for (int x = 0; x < Size; x++)
                {
                    bool on = x < row.Length && row[x] == '#';
                    px[(Size - 1 - y) * Size + x] = new Color32(255, 255, 255, (byte)(on ? 255 : 0));
                }
            }
            tex.SetPixels32(px); tex.Apply(false);
            Cache[key] = tex;
            return tex;
        }
