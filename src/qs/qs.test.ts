import { describe, expect, it } from "vitest";
import fixtureJson from "./demo/fixture.json";
import { DemoSource, type Clock, type Fixture } from "./demo";
import { EMPLOYERS, EMPLOYERS_ARE_PLACEHOLDERS } from "./employers";
import { EVENT_LABELS, FEATURES, LIVE_SIGNALS, OUTCOME_LABELS, PRINCIPLES, fmt } from "./labels";
import { assertBrowserSafeKey, readConfig } from "./source";
import { applyMessage, emptyView, orderedRecords, questionBands } from "./store";
import { smooth, yOf } from "./charts";
import type { QsMessage, Session } from "./types";

const fixture = fixtureJson as unknown as Fixture;
const session: Session = { id: "s1", status: "created", candidate_id: "c1", candidate_pseudonym: "C-000001" };

function fakeClock() {
  let t = 0;
  const timers: (() => void)[] = [];
  const clock: Clock = { now: () => t, every: (_ms, fn) => { timers.push(fn); return () => {}; } };
  return { clock, advance(ms: number) { t += ms; timers.forEach((f) => f()); } };
}

describe("store", () => {
  it("keeps windows in seq order and drops duplicates", () => {
    const v = emptyView(session);
    const w = (seq: number) => ({ event: "window", payload: { seq, t_start: seq / 2, t_end: seq / 2 + 1, question_key: null, features: {}, rel: null, freeze: null } }) as QsMessage;
    [w(0), w(2), w(1), w(2), w(3)].forEach((m) => applyMessage(v, m));
    expect(v.windows.map((x) => x.seq)).toEqual([0, 1, 2, 3]);
    expect(v.lastSeq).toBe(3);
  });

  it("tracks session status from events and builds question bands", () => {
    const v = emptyView(session);
    applyMessage(v, { event: "event", payload: { t: 1, type: "question_shown", question_key: "p1", payload: null } });
    expect(v.session.status).toBe("live");
    expect(questionBands(v)).toEqual([{ key: "p1", t0: 1, t1: null }]);
    applyMessage(v, { event: "event", payload: { t: 9, type: "session_end", question_key: null, payload: null } });
    expect(v.session.status).toBe("ended");
  });
});

describe("demo source replays the pipeline output through the store", () => {
  it("delivers windows, events, records and a baseline in session order, then ends", async () => {
    const { clock, advance } = fakeClock();
    const src = new DemoSource(fixture, clock, false);
    const sessions = await src.listSessions();
    expect(sessions.filter((s) => s.status === "live")).toHaveLength(1);
    const live = sessions.find((s) => s.status === "live")!;
    const snap = await src.load(live.id);
    const view = emptyView(snap.session);
    const kinds = new Set<string>();
    src.subscribe(live.id, (m) => { kinds.add(m.event); applyMessage(view, m); });
    advance(3000);   // calibration plays 4x: 12 s of session
    expect(view.windows.length).toBeGreaterThan(15);
    expect(view.records.size).toBe(0);
    for (let i = 0; i < 160; i++) advance(1000);
    expect([...kinds].sort()).toEqual(["baseline", "event", "record", "window"]);
    expect(orderedRecords(view).map((r) => r.question_key)).toEqual(["p1", "p2", "p3", "p4", "p5"]);
    expect(view.session.status).toBe("ended");
    expect(view.baseline?.status).toBe("ok");
    expect((await src.listSessions()).find((s) => s.id === live.id)?.status).toBe("ended");
  });

  it("has a labelled demo summary whose evidence comes from the records", async () => {
    const src = new DemoSource(fixture, fakeClock().clock, false);
    const live = (await src.listSessions()).find((s) => s.status === "live")!;
    const s = await src.requestSummary(live.id);
    expect(s.status).toBe("demo");
    expect(s.reason).toMatch(/not generated by Gemini/i);
    expect(s.summary!.observations.length).toBeGreaterThan(3);
    for (const o of s.summary!.observations) expect(o.question_keys.length).toBeGreaterThan(0);
  });

  it("uses pseudonymous ids only", () => {
    const text = JSON.stringify(fixture);
    for (const s of fixture.sessions) expect(s.session.candidate_pseudonym).toMatch(/^C-[0-9A-F]{6}$/);
    expect(text).not.toMatch(/display_name|email/);
  });
});

// Words that would turn a measurement into a verdict, a guess at a mental state, or a diagnosis.
const VERDICT = /\b(hire|hiring decision|reject|suitab|unsuitab|recommend|nervous|anxious|anxiety|stress|panic|fear|scared|confiden|liar|lying|honest|competen|intelligen|personality|disorder|parkinson|diagnos(?!is)|score|rating|rank|pass|fail)\w*/i;

describe("copy describes measurements, not verdicts", () => {
  const strings = [
    ...Object.values(FEATURES).flatMap((f) => [f.short, f.long]),
    ...Object.values(LIVE_SIGNALS).flatMap((s) => [s.label, s.note]),
    ...Object.values(EVENT_LABELS), ...Object.values(OUTCOME_LABELS),
  ];
  it.each(strings)("%s", (s) => { expect(s).not.toMatch(VERDICT); });

  it("the demo summary observations pass the same check", () => {
    const sum = fixture.sessions.find((s) => s.summary)!.summary!.summary!;
    for (const o of [...sum.observations, ...sum.data_quality]) expect(o.statement).not.toMatch(VERDICT);
  });

  it("principles say there is no score or hire/reject call", () => {
    expect(PRINCIPLES.map((p) => p[1]).join(" ")).toMatch(/no score/i);
  });
});

describe("employers band", () => {
  it("is driven by one list, flagged as placeholders", () => {
    expect(EMPLOYERS_ARE_PLACEHOLDERS).toBe(true);
    expect(EMPLOYERS.length).toBeGreaterThan(3);
    for (const e of EMPLOYERS) expect(e.logo).toBeUndefined();
  });
});

describe("config and keys", () => {
  it("demo mode is on without an API URL, or with ?demo", () => {
    expect(readConfig({}, "").demo).toBe(true);
    expect(readConfig({ VITE_QS_API_URL: "https://api.example" }, "").demo).toBe(false);
    expect(readConfig({ VITE_QS_API_URL: "https://api.example" }, "?demo").demo).toBe(true);
  });

  it("refuses secret or service_role keys in the browser", () => {
    expect(() => assertBrowserSafeKey("sb_secret_abc")).toThrow();
    const body = btoa(JSON.stringify({ role: "service_role" }));
    expect(() => assertBrowserSafeKey(`x.${body}.y`)).toThrow();
    const anon = btoa(JSON.stringify({ role: "anon" }));
    expect(() => assertBrowserSafeKey(`x.${anon}.y`)).not.toThrow();
    expect(() => assertBrowserSafeKey("sb_publishable_abc")).not.toThrow();
  });
});

describe("chart helpers", () => {
  it("log2 axis puts 2x and 0.5x equally far from 1x", () => {
    const one = yOf(1, 0, 100);
    expect(one - yOf(2, 0, 100)).toBeCloseTo(yOf(0.5, 0, 100) - one);
  });
  it("smoothing keeps gaps and averages in log space", () => {
    expect(smooth([1, null, 4], 1)).toEqual([1, null, 4]);
    expect(smooth([1, 4], 1)[0]).toBeCloseTo(2);
  });
  it("formats ratios and shares", () => {
    expect(fmt(2.345, "×")).toBe("2.35×");
    expect(fmt(0.97, "")).toBe("97%");
    expect(fmt(null)).toBe("—");
  });
});
